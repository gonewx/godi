package main

import (
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/packages"
)

// generatedHeader is the first line genlib emits on every container. A file
// whose first line equals it is treated as a previous godi-gen product: the
// type-check gate stubs it out so a stale Root cannot collide with the fresh
// one being checked.
const generatedHeader = "// Code generated by godi-gen; DO NOT EDIT."

// hasGeneratedHeader reports whether src is a previous godi-gen product: its
// first line equals generatedHeader. The file name plays no part.
func hasGeneratedHeader(src []byte) bool {
	firstLine, _, _ := strings.Cut(string(src), "\n")
	return strings.TrimSuffix(firstLine, "\r") == generatedHeader
}

// generatedFileOverlay scans dir for *.go files whose first line equals
// generatedHeader and maps each (by its path under dir) to a stub holding only
// its package clause, "package <name>\n". <name> is the file's own package
// clause; when that cannot be parsed, the package clause of the first
// non-generated .go file in dir is used instead. A missing dir yields an empty
// overlay.
func generatedFileOverlay(dir string) (map[string][]byte, error) {
	overlay := make(map[string][]byte)
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return overlay, nil
		}
		return nil, fmt.Errorf("scan %q for generated files: %w", dir, err)
	}

	var generated []string
	fallbackPkg := ""
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		if hasGeneratedHeader(data) {
			generated = append(generated, path)
			continue
		}
		if fallbackPkg == "" {
			fallbackPkg = packageClause(path, data)
		}
	}

	for _, path := range generated {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		name := packageClause(path, data)
		if name == "" {
			name = fallbackPkg
		}
		if name == "" {
			return nil, fmt.Errorf("generated file %s: cannot determine its package name", path)
		}
		overlay[path] = []byte("package " + name + "\n")
	}
	return overlay, nil
}

// packageClause returns the package name declared by src, or "" when the
// package clause does not parse.
func packageClause(path string, src []byte) string {
	f, err := parser.ParseFile(token.NewFileSet(), path, src, parser.PackageClauseOnly)
	if err != nil || f.Name == nil {
		return ""
	}
	return f.Name.Name
}

// typeCheckOutput type-checks the emitted container src as it will be compiled,
// without writing anything to disk (format.Source in genlib only proves it
// parses). The checked file's location follows where the container will live:
//
//   - outPath != "": outPath itself, loaded with its directory's package;
//   - stdout mode, samePkg: a synthetic zz_godi_typecheck_gen.go beside the
//     registration sources;
//   - stdout mode, other package: container_gen.go in a synthetic
//     _godi_typecheck_<pkgName> subdirectory of srcDir that never touches disk.
//
// Previously generated files in that directory are stubbed to bare package
// clauses (generatedFileOverlay) so a stale Root does not collide with the
// fresh one. A second packages.Load is required: the registration package
// usually does not import godi/runtime, so the first load's type information
// cannot serve as the importer for the container.
func typeCheckOutput(srcDir, pkgName, outPath string, samePkg bool, src []byte) error {
	absSrcDir, err := filepath.Abs(srcDir)
	if err != nil {
		return fmt.Errorf("generated container does not type-check (no output written): resolve %q: %w", srcDir, err)
	}

	var target, loadDir, pattern string
	switch {
	case outPath != "":
		target, err = filepath.Abs(outPath)
		if err != nil {
			return fmt.Errorf("generated container does not type-check (no output written): resolve %q: %w", outPath, err)
		}
		loadDir, pattern = filepath.Dir(target), "."
	case samePkg:
		target = filepath.Join(absSrcDir, "zz_godi_typecheck_gen.go")
		loadDir, pattern = absSrcDir, "."
	default:
		sub := "_godi_typecheck_" + pkgName
		target = filepath.Join(absSrcDir, sub, "container_gen.go")
		loadDir, pattern = absSrcDir, "./"+sub
	}

	overlay, err := generatedFileOverlay(filepath.Dir(target))
	if err != nil {
		return fmt.Errorf("generated container does not type-check (no output written): %w", err)
	}
	overlay[target] = src

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports |
			packages.NeedDeps,
		Dir:     loadDir,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, pattern)
	if err != nil {
		return fmt.Errorf("generated container does not type-check (no output written):\n%v", err)
	}
	if len(pkgs) == 0 {
		return fmt.Errorf("generated container does not type-check (no output written):\nno package loaded for %s", target)
	}
	var msgs []string
	for _, p := range pkgs {
		for _, e := range p.Errors {
			msgs = append(msgs, e.Error())
		}
	}
	if len(msgs) > 0 {
		return fmt.Errorf("generated container does not type-check (no output written):\n%s",
			strings.Join(msgs, "\n"))
	}
	return nil
}
