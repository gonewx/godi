// Command gen reads wiring/manifest.txt and writes wiring/registrations_gen.go,
// materialising a closed IRepository[T] registration (and reflection-free direct
// wiring) for every listed element type.
//
// Run from the module root:
//
//	go run ./wiring/gen
//
// This is the codegen route's "compiler": it turns the single manifest (the Go
// stand-in for dotnet's one open-generic registration) into concrete closed
// registrations the Go compiler can type-check.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
	"text/template"
)

const (
	manifestPath = "wiring/manifest.txt"
	outPath      = "wiring/registrations_gen.go"
)

var tmpl = template.Must(template.New("gen").Parse(`// Code generated by "go run ./wiring/gen"; DO NOT EDIT.
package wiring

import (
	"godipoc/opengeneric/domain"
	"godipoc/opengeneric/godi"
)

// RegisterGeneratedRepositories materialises a closed IRepository[T] registration
// for every element type in wiring/manifest.txt. This is the codegen equivalent
// of dotnet's single open-generic registration:
//
//	services.AddSingleton(typeof(IRepository<>), typeof(Repository<>));
func RegisterGeneratedRepositories(c *godi.Container) {
{{- range .}}
	AddRepository[domain.{{.}}](c)
{{- end}}
}

// AppRepositories is a generated, reflection-free holder wiring every closed
// repository directly (wire-style): no container, no map, fully compile-time safe.
type AppRepositories struct {
{{- range .}}
	{{.}} domain.IRepository[domain.{{.}}]
{{- end}}
}

// NewAppRepositories builds all repositories with zero reflection.
func NewAppRepositories(log domain.Logger) AppRepositories {
	return AppRepositories{
{{- range .}}
		{{.}}: domain.NewRepository[domain.{{.}}](log),
{{- end}}
	}
}
`))

func main() {
	types, err := readManifest(manifestPath)
	if err != nil {
		fail(err)
	}
	if len(types) == 0 {
		fail(fmt.Errorf("no element types found in %s", manifestPath))
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, types); err != nil {
		fail(err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fail(fmt.Errorf("gofmt generated source: %w", err))
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("gen: wrote %s for %d type(s): %s\n", outPath, len(types), strings.Join(types, ", "))
}

func readManifest(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var out []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		out = append(out, line)
	}
	return out, sc.Err()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
