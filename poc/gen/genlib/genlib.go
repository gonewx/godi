// Package genlib turns a validated plan.Registry into wiring source code.
// Generate refuses to emit anything for an invalid graph — validation is a hard
// gate, mirroring (and shifting left) dotnet's ValidateOnBuild.
package genlib

import (
	"fmt"
	"go/format"
	"strings"

	"godipoc/gen/plan"
)

const header = `// Code generated by godipoc/gen; DO NOT EDIT.
package app

import (
	"godipoc/gen/domain"
)
`

// Generate validates reg, then emits gofmt'd container source. On an invalid
// graph it returns an error and NO code.
func Generate(reg *plan.Registry) ([]byte, error) {
	if errs := reg.Validate(); len(errs) > 0 {
		var b strings.Builder
		b.WriteString("registration graph invalid; refusing to generate:\n")
		for _, e := range errs {
			fmt.Fprintf(&b, "  - %v\n", e)
		}
		return nil, fmt.Errorf("%s", b.String())
	}

	var b strings.Builder
	b.WriteString(header)
	emitRoot(&b, reg)
	emitScope(&b, reg)
	emitGet(&b, reg)
	emitEnums(&b, reg)
	emitKeyed(&b, reg)

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt generated code: %w\n--- raw ---\n%s", err, b.String())
	}
	return src, nil
}

// accessExpr returns source to obtain dependency depName from a given context:
// "root" (inside NewRoot) or "scope" (inside a *Scope method).
func accessExpr(reg *plan.Registry, depName, ctx string) string {
	d, _ := reg.Lookup(depName) // existence guaranteed by Validate
	switch d.Lifetime {
	case plan.Singleton:
		if ctx == "root" {
			return "r.f_" + d.Name // already built earlier in topo order
		}
		return "s.root." + d.Name + "()"
	case plan.Scoped:
		return "s." + d.Name + "()"
	default: // Transient
		return "s.New" + d.Name + "()"
	}
}

func depArgs(reg *plan.Registry, s plan.Service, ctx string) string {
	parts := make([]string, 0, len(s.Deps))
	for _, dep := range s.Deps {
		parts = append(parts, accessExpr(reg, dep, ctx))
	}
	return strings.Join(parts, ", ")
}

func emitRoot(b *strings.Builder, reg *plan.Registry) {
	singles := reg.SingletonsTopo()

	b.WriteString("\ntype Root struct {\n")
	for _, s := range singles {
		fmt.Fprintf(b, "\tf_%s %s\n", s.Name, s.GoType)
	}
	b.WriteString("\tdisp *disposer\n}\n\n")

	b.WriteString("func NewRoot() *Root {\n\tr := &Root{disp: newDisposer()}\n")
	for _, s := range singles {
		fmt.Fprintf(b, "\tr.f_%s = %s(%s)\n", s.Name, s.Ctor, depArgs(reg, s, "root"))
		if s.Disposable {
			fmt.Fprintf(b, "\tr.disp.track(%q, r.f_%s)\n", s.Name, s.Name)
		}
	}
	b.WriteString("\treturn r\n}\n\n")

	for _, s := range singles {
		fmt.Fprintf(b, "func (r *Root) %s() %s { return r.f_%s }\n", s.Name, s.GoType, s.Name)
	}
	b.WriteString("\nfunc (r *Root) Close() error          { return r.disp.closeAll() }\n")
	b.WriteString("func (r *Root) DisposedOrder() []string { return r.disp.order() }\n")
}

func emitScope(b *strings.Builder, reg *plan.Registry) {
	var scoped, transient []plan.Service
	for _, s := range reg.Services() {
		switch s.Lifetime {
		case plan.Scoped:
			scoped = append(scoped, s)
		case plan.Transient:
			transient = append(transient, s)
		}
	}

	b.WriteString("\ntype Scope struct {\n\troot *Root\n")
	for _, s := range scoped {
		fmt.Fprintf(b, "\tf_%s %s\n", s.Name, s.GoType)
	}
	b.WriteString("\tdisp *disposer\n}\n\n")

	b.WriteString("func (r *Root) NewScope() *Scope { return &Scope{root: r, disp: newDisposer()} }\n")
	b.WriteString("func (s *Scope) Root() *Root     { return s.root }\n\n")

	for _, s := range scoped {
		fmt.Fprintf(b, "func (s *Scope) %s() %s {\n", s.Name, s.GoType)
		fmt.Fprintf(b, "\tif s.f_%s == nil {\n", s.Name)
		fmt.Fprintf(b, "\t\ts.f_%s = %s(%s)\n", s.Name, s.Ctor, depArgs(reg, s, "scope"))
		if s.Disposable {
			fmt.Fprintf(b, "\t\ts.disp.track(%q, s.f_%s)\n", s.Name, s.Name)
		}
		fmt.Fprintf(b, "\t}\n\treturn s.f_%s\n}\n\n", s.Name)
	}

	for _, s := range transient {
		fmt.Fprintf(b, "func (s *Scope) New%s() %s { return %s(%s) }\n",
			s.Name, s.GoType, s.Ctor, depArgs(reg, s, "scope"))
	}

	b.WriteString("\nfunc (s *Scope) Close() error          { return s.disp.closeAll() }\n")
	b.WriteString("func (s *Scope) DisposedOrder() []string { return s.disp.order() }\n")
}

func emitGet(b *strings.Builder, reg *plan.Registry) {
	b.WriteString("\n// Get is the reflection-free generic resolver (type switch over services).\n")
	b.WriteString("func Get[T any](s *Scope) (T, bool) {\n\tvar zero T\n\tswitch any(zero).(type) {\n")
	for _, s := range reg.Services() {
		// The zero-value type switch only dispatches non-interface T; our
		// lifetime services are all pointer types, so guard on that.
		if !strings.HasPrefix(s.GoType, "*") {
			continue
		}
		var expr string
		switch s.Lifetime {
		case plan.Singleton:
			expr = "s.root." + s.Name + "()"
		case plan.Scoped:
			expr = "s." + s.Name + "()"
		default:
			expr = "s.New" + s.Name + "()"
		}
		fmt.Fprintf(b, "\tcase %s:\n\t\treturn any(%s).(T), true\n", s.GoType, expr)
	}
	b.WriteString("\t}\n\treturn zero, false\n}\n")
}

func emitEnums(b *strings.Builder, reg *plan.Registry) {
	for _, e := range reg.Enums() {
		fmt.Fprintf(b, "\n// %s resolves IEnumerable[%s] (all impls, registration order).\n", e.Accessor, e.IfaceType)
		fmt.Fprintf(b, "func (s *Scope) %s() []%s {\n\treturn []%s{\n", e.Accessor, e.IfaceType, e.IfaceType)
		for _, c := range e.Ctors {
			fmt.Fprintf(b, "\t\t%s,\n", c)
		}
		b.WriteString("\t}\n}\n")
	}
}

func emitKeyed(b *strings.Builder, reg *plan.Registry) {
	for _, k := range reg.KeyedGroups() {
		fmt.Fprintf(b, "\n// %s resolves a keyed %s (dotnet GetKeyedService).\n", k.Accessor, k.IfaceType)
		fmt.Fprintf(b, "func (s *Scope) %s(key string) (%s, bool) {\n\tswitch key {\n", k.Accessor, k.IfaceType)
		for _, it := range k.Items {
			fmt.Fprintf(b, "\tcase %q:\n\t\treturn %s, true\n", it.Key, it.Ctor)
		}
		fmt.Fprintf(b, "\t}\n\tvar zero %s\n\treturn zero, false\n}\n", k.IfaceType)
	}
}
