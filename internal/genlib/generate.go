package genlib

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/gonewx/godi/plan"
)

// Generate is the unique code-emission path (AD-2). It validates the
// registry first; a non-empty Validate result aborts emission and returns
// nil output + error (AD-3: bad graph → zero-byte code).
//
// The emitted container is a self-contained package with no external imports.
// Fields are typed as `any` because the plan model uses string-based type
// references (D3: canonical type facts come from go/types in Story 2.1).
// The full godi.Provider interface assertion lands in Story 1.5 when the
// codegen container is wired into the conformance suite.
func Generate(reg *plan.Registry, pkgName string) ([]byte, error) {
	if errs := reg.Validate(); len(errs) > 0 {
		msgs := make([]string, len(errs))
		for i, e := range errs {
			msgs[i] = e.Error()
		}
		return nil, fmt.Errorf("validation failed:\n%s", strings.Join(msgs, "\n"))
	}

	var buf bytes.Buffer
	services := reg.Services()
	emitHeader(&buf, pkgName)
	emitRootStruct(&buf, services)
	emitNewRoot(&buf)
	emitAccessors(&buf, services)
	emitClose(&buf)

	src, fmtErr := format.Source(buf.Bytes())
	if fmtErr != nil {
		return nil, fmt.Errorf("format generated code: %w", fmtErr)
	}
	return src, nil
}

func emitHeader(buf *bytes.Buffer, pkgName string) {
	fmt.Fprintf(buf, "// Code generated by godi-gen; DO NOT EDIT.\n")
	fmt.Fprintf(buf, "package %s\n\n", pkgName)
}

func emitRootStruct(buf *bytes.Buffer, services []plan.Service) {
	fmt.Fprintf(buf, "type Root struct {\n")
	for _, s := range services {
		if s.Lifetime == plan.Singleton {
			fmt.Fprintf(buf, "\tf_%s any\n", s.Name)
		}
	}
	fmt.Fprintf(buf, "}\n\n")
}

func emitNewRoot(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "func NewRoot() *Root {\n")
	fmt.Fprintf(buf, "\treturn &Root{}\n")
	fmt.Fprintf(buf, "}\n\n")
}

func emitAccessors(buf *bytes.Buffer, services []plan.Service) {
	for _, s := range services {
		if s.Lifetime == plan.Singleton {
			fmt.Fprintf(buf, "func (r *Root) %s() any { return r.f_%s }\n\n", s.Name, s.Name)
		}
	}
}

func emitClose(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "func (r *Root) Close() error { return nil }\n")
}
