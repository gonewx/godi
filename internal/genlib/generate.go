func concatServices(slices ...[]plan.Service) []plan.Service {
	var total int
	for _, s := range slices {
		total += len(s)
	}
	out := make([]plan.Service, 0, total)
	for _, s := range slices {
		out = append(out, s...)
	}
	return out
}
