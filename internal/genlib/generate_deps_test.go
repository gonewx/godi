// Story 2.1 (AC1/AC3) — genlib emit: dependency wiring in topo order +
// trailing-error propagation + NewRoot signature evolution (Task 2).
//
// Epic 1's emit wired no-dep singletons as `r.f_X = Ctor()`. This story evolves
// emitNewRoot to (a) wire dependencies as constructor arguments
// (`r.f_X = Ctor(r.f_Dep)`), (b) order them by SingletonsTopo so a dependency is
// built first, and (c) propagate a trailing constructor error up through the new
// `NewRoot() (*Root, error)` signature (D-1). Form B is inlined as
// `r.f_X = (factoryExpr)(r)` (D-2).
//
// The behavioral assertions (dependency args, topo order, error form, new
// signature) are reinforced by committed golden files for the form-A-with-deps
// and form-B containers (testdata/deps-container.golden, formb-container.golden).
//
// API CONTRACT (unchanged signature, evolved emit shape):
//
//	genlib.Generate(reg *plan.Registry, pkgName string) ([]byte, error)
//	emit shape: NewRoot() (*Root, error); deps as `r.f_X = Ctor(r.f_Dep)`;
//	error ctor as `r.f_X, err = Ctor(...); if err != nil { return nil, err }`;
//	form B as `r.f_X = (factoryExpr)(r)`.
package genlib_test

import (
	"go/format"
	"strings"
	"testing"

	"github.com/gonewx/godi/internal/genlib"
	"github.com/gonewx/godi/internal/testutil"
	"github.com/gonewx/godi/plan"
)

// depsRegistry is a two-singleton graph where Consumer depends on Dep — the
// minimum-viable dependency wiring case.
func depsRegistry() *plan.Registry {
	reg := plan.NewRegistry()
	reg.Imports = []string{"example.com/svc"}
	reg.Service(plan.Service{
		Name:     "Dep",
		GoType:   "*svc.Dep",
		Ctor:     "svc.NewDep",
		Lifetime: plan.Singleton,
	})
	reg.Service(plan.Service{
		Name:     "Consumer",
		GoType:   "*svc.Consumer",
		Ctor:     "svc.NewConsumer",
		Lifetime: plan.Singleton,
		Deps:     []string{"Dep"},
	})
	return reg
}

// TestGenerateDeps_EmitsDependencyArgumentsInTopoOrder covers 2.1-EMIT-001 (AC1).
//
// NewRoot must construct Consumer with its dependency field as an argument, and
// Dep must be wired before Consumer (topo order).
func TestGenerateDeps_EmitsDependencyArgumentsInTopoOrder(t *testing.T) {
	src, err := genlib.Generate(depsRegistry(), "codegen")
	testutil.NoError(t, err)
	code := string(src)

	testutil.True(t, strings.Contains(code, "r.f_Consumer = svc.NewConsumer(r.f_Dep)"),
		"NewRoot must wire Consumer with its dependency: r.f_Consumer = svc.NewConsumer(r.f_Dep)")

	depIdx := strings.Index(code, "r.f_Dep = svc.NewDep()")
	consIdx := strings.Index(code, "r.f_Consumer = svc.NewConsumer(r.f_Dep)")
	testutil.True(t, depIdx >= 0 && depIdx < consIdx,
		"Dep must be wired before Consumer (SingletonsTopo dependency order)")
}

// TestGenerateDeps_NewRootReturnsError covers 2.1-EMIT-002 (AC1).
//
// NewRoot evolves to (*Root, error) so a constructor's trailing error can
// propagate (D-1: unified signature, one-time evolution across both providers).
func TestGenerateDeps_NewRootReturnsError(t *testing.T) {
	src, err := genlib.Generate(depsRegistry(), "codegen")
	testutil.NoError(t, err)

	testutil.True(t, strings.Contains(string(src), "func NewRoot() (*Root, error)"),
		"NewRoot must evolve to (*Root, error) for constructor error propagation (D-1)")
}

// TestGenerateDeps_PropagatesCtorError covers 2.1-EMIT-003 (AC1).
//
// A singleton whose constructor returns a trailing error (CtorErr) must be
// emitted in comma-err form with an early `return nil, err` so the error
// propagates out of NewRoot (AD-8 error pass-through).
func TestGenerateDeps_PropagatesCtorError(t *testing.T) {
	reg := plan.NewRegistry()
	reg.Imports = []string{"example.com/svc"}
	reg.Service(plan.Service{
		Name:     "Fallible",
		GoType:   "*svc.Fallible",
		Ctor:     "svc.NewFallible",
		Lifetime: plan.Singleton,
		CtorErr:  true,
	})

	src, err := genlib.Generate(reg, "codegen")
	testutil.NoError(t, err)
	code := string(src)

	testutil.True(t, strings.Contains(code, "r.f_Fallible, err = svc.NewFallible()"),
		"error-returning ctor must use comma-err assignment form")
	testutil.True(t, strings.Contains(code, "return nil, err"),
		"a trailing-error ctor must propagate the error up from NewRoot")
}

// TestGenerateDeps_OutputIsFormattedAndHeaded covers 2.1-EMIT-005 (AC3).
//
// Regardless of dependency wiring, the emitted source stays gofmt-legal and
// keeps the canonical "Code generated by" header (regression guard).
func TestGenerateDeps_OutputIsFormattedAndHeaded(t *testing.T) {
	src, err := genlib.Generate(depsRegistry(), "codegen")
	testutil.NoError(t, err)

	_, fmtErr := format.Source(src)
	testutil.NoError(t, fmtErr)

	first := strings.SplitN(string(src), "\n", 2)[0]
	testutil.True(t, strings.HasPrefix(first, "// Code generated by"),
		"first line must be the '// Code generated by ...; DO NOT EDIT.' header")
}

