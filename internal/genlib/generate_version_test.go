package genlib_test

import (
	"strings"
	"testing"

	"github.com/gonewx/godi/internal/genlib"
)

func headerLines(t *testing.T, src []byte) []string {
	t.Helper()
	lines := strings.SplitN(string(src), "\n", 4)
	if len(lines) < 4 {
		t.Fatalf("output too short:\n%s", src)
	}
	return lines
}

// TestGenerate_HeaderCarriesGeneratorVersion: line 1 is the unchanged generated
// marker, line 2 names the generator version, and the package clause follows.
func TestGenerate_HeaderCarriesGeneratorVersion(t *testing.T) {
	src, err := genlib.Generate(singleServiceRegistry(), "container", genlib.WithGeneratorVersion("v9.8.7"))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	lines := headerLines(t, src)
	if want := "// Code generated by godi-gen; DO NOT EDIT."; lines[0] != want {
		t.Fatalf("line 1 = %q, want %q", lines[0], want)
	}
	if want := "// godi-gen version: v9.8.7"; lines[1] != want {
		t.Fatalf("line 2 = %q, want %q", lines[1], want)
	}
	if want := "package container"; lines[2] != want {
		t.Fatalf("line 3 = %q, want %q", lines[2], want)
	}
}

// TestGenerate_HeaderVersionDefaultsToDevel: without a version the header says
// "(devel)", so the header always has the same two-line shape.
func TestGenerate_HeaderVersionDefaultsToDevel(t *testing.T) {
	src, err := genlib.Generate(singleServiceRegistry(), "container")
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if want := "// godi-gen version: (devel)"; headerLines(t, src)[1] != want {
		t.Fatalf("line 2 = %q, want %q", headerLines(t, src)[1], want)
	}
}
